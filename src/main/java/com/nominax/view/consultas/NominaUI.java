    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        try {
            int option = filtrarPor.getSelectedIndex();
            DefaultTableModel modelo = (DefaultTableModel) modeloTabla.getModel();
            modelo.setRowCount(0);
            
            switch(option){
                case 0:
                    Date fecha = fechaSeleccionada.getDate();
                    Calendar calendario = Calendar.getInstance();
                    calendario.setTime(fecha);
                    
                    int mes = calendario.get(Calendar.MONTH) + 1;
                    int anio = calendario.get(Calendar.YEAR);

                    List<Nomina> nominas = this.db.buscarPorMesYAnio(mes, anio);
                    agregarFilas(modelo, nominas);
                    break;
                case 1:
                     List<Nomina> nominaUsuario = this.db.buscarPorEmpleado(txtUserId.getText());
                     agregarFilas(modelo, nominaUsuario);
                     break;
                default:
                    JOptionPane.showMessageDialog(this, "Opción no válida", "Error", JOptionPane.ERROR_MESSAGE);
                    break;
            }
        } catch (IOException ex) {
                 JOptionPane.showMessageDialog(this,
                     String.format("Error al consultar la base de datos"),
                     "Error",
                     JOptionPane.ERROR_MESSAGE
                 );
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void txtUserIdKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtUserIdKeyTyped
        char c = evt.getKeyChar();
        if (!Character.isDigit(c) && c != KeyEvent.VK_BACK_SPACE) {
            evt.consume();
        }
    }//GEN-LAST:event_txtUserIdKeyTyped

    private void filtrarPorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_filtrarPorActionPerformed
        int option = filtrarPor.getSelectedIndex();
        
        
        switch (option) {
            case 0:
                txtUserId.setEnabled(false);
                txtUserId.setOpaque(false);
                fechaSeleccionada.setEnabled(true);
                fechaSeleccionada.setOpaque(false);
                break;
            case 1:
                txtUserId.setEnabled(true);
                txtUserId.setOpaque(true);
                fechaSeleccionada.setEnabled(false);
                fechaSeleccionada.setOpaque(true);
                break;
            default:
                throw new AssertionError();
        }
    }//GEN-LAST:event_filtrarPorActionPerformed

   
    private void agregarFilas(DefaultTableModel modelo, List<Nomina> nominas){
         if(!nominas.isEmpty()){
                        nominas.stream()
                                .forEach(nomina -> {
                                    Object[] fila = {
                                        nomina.getIdEmpleado(),
                                        nomina.getFecha(),
                                        nomina.getSalarioBase(),
                                        nomina.getDescuentoARS(),
                                        nomina.getDescuentoAFP(),
                                        nomina.getDescuentoCooperativa(),
                                        nomina.getDescuentoISR(),
                                        nomina.getSalarioNeto(),
                                        nomina.getStatusNomina()
                                    };
                                    modelo.addRow(fila);
                                });
                         }
    }
    
