    private void cargarDatos(String query, Integer limite) throws IOException {
        DefaultTableModel modelo = (DefaultTableModel) modeloTabla.getModel();
        modelo.setRowCount(0);
        if(query.isEmpty() && limite.equals(0)){
            if (departamentos != null) {
                for (Departamento puesto : departamentos) {
                    Object[] fila = {
                        puesto.getId(),
                        puesto.getDescripcion()
                    };
                    modelo.addRow(fila);
                }
            }
            return; 
        }
        if (!query.isEmpty() || limite != null) {
            departamentos.stream()
                .filter(departamento -> departamento.getDescripcion().toLowerCase().contains(query.toLowerCase()))
                .limit(limite != null && !limite.equals(0) ? limite : departamentos.size())
                .forEach(departamento -> {
                    Object[] fila = {
                        departamento.getId(),
                        departamento.getDescripcion()
                    };
                    modelo.addRow(fila);
                });
        }
    }
    
