    private void txtUsuarioKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtUsuarioKeyPressed
        if(evt.getKeyCode() ==  evt.VK_ENTER){
            try {
                Optional<Usuario> usuarioEncontrado = this.userDb.buscarPorUsuario(txtUsuario.getText());
                if(usuarioEncontrado.isEmpty()) return;
                
                Usuario user = usuarioEncontrado.get();
                
                txtUsuario.setEnabled(false);
                
                txtNombre.setText(user.getNombre());
                txtApellidos.setText(user.getApellidos());
                txtCorreo.setText(user.getEmail());
                cmbRole.setSelectedIndex(user.getNivelDeAcceso());
                
                lblMensajeEstado.setText("Actualizando registro."); 
                lblMensajeEstado.setForeground(Color.RED);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al buscar el usuario: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_txtUsuarioKeyPressed

