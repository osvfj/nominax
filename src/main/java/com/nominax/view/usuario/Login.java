    private void entrarBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_entrarBtnActionPerformed
        String usuario = txtUsuario.getText();
        String password = new String(txtPassword.getPassword());
        
        try {
            Optional<Usuario> usuarioEncontrado = this.userDb.validarCredenciales(usuario, password);
            
            if(usuarioEncontrado.isEmpty()){
                lblMensajeEstado.setText("Usuario o contraseña incorrecta"); 
                lblMensajeEstado.setForeground(Color.RED); 
                return;
            }
            
            Usuario user = usuarioEncontrado.get();
            
                      
            MenuPrincipal menu = new MenuPrincipal(user.getNivelDeAcceso(), user);
            menu.setVisible(true);
            menu.setLocationRelativeTo(null);
            
            this.dispose();
        } catch (Exception e) {
        }
        
        
        
    }//GEN-LAST:event_entrarBtnActionPerformed

    private void txtPasswordKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPasswordKeyPressed
         if(evt.getKeyCode() ==  evt.VK_ENTER){
            entrarBtn.doClick();
        }
    }//GEN-LAST:event_txtPasswordKeyPressed

