    private void registrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registrarActionPerformed
      

        int id = Integer.parseInt(txtId.getText());
        String descripcion = txtNombre.getText();
        
        try {  
             Optional<Puesto> departamentoEncontrado = this.db.buscarPorId(id);
             if(!departamentoEncontrado.isEmpty()) {
                 Puesto departamento = departamentoEncontrado.get();
            
                 if(!this.validarCampos()) return;
                 
                 departamento.setNombre(descripcion);

                 this.db.guardar(departamento);
                 JOptionPane.showMessageDialog(this, "Puesto actualizado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                 reiniciarFormulario();
                 try {
                    this.updateId();
                } catch (IOException ex) {
                    Logger.getLogger(PuestoUI.class.getName()).log(Level.SEVERE, null, ex);
                }
                 return;
             }
            
             
            if(!this.validarCampos()) return;
            
            Puesto nuevoPuesto = new Puesto(id, descripcion);
            this.db.guardar(nuevoPuesto);
            JOptionPane.showMessageDialog(this, "Puesto guardado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        } catch (HeadlessException | IOException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar usuario: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            this.reiniciarFormulario();
            try {
                this.updateId();
            } catch (IOException ex) {
                Logger.getLogger(PuestoUI.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_registrarActionPerformed

