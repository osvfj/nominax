    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
            Date fecha = fechaSeleccionada.getDate();
            Calendar calendario = Calendar.getInstance();
            calendario.setTime(fecha);
            
            GeneradorNominas generadorDeNomina = new GeneradorNominas();

            int mes = calendario.get(Calendar.MONTH) + 1;
            int anio = calendario.get(Calendar.YEAR);
            
            int confirmar = JOptionPane.showConfirmDialog(this, String.format("¿Realmente quieres generar la nómina de %d del %d?", mes, anio), "Crear nómina", JOptionPane.YES_NO_OPTION);
            
            if(confirmar == JOptionPane.YES_OPTION){
                try {
                    generadorDeNomina.generarNominas(mes, anio);
               } catch (IllegalStateException ex) {
                    JOptionPane.showMessageDialog(this,
                        String.format("Ya existe un reporte para este mes"),
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                    );
                } catch (IOException ex) {
                    JOptionPane.showMessageDialog(this,
                        String.format("Erorr al consultar la base de datos"),
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                    );
                }
            }
    }//GEN-LAST:event_btnConsultarActionPerformed

  
    
