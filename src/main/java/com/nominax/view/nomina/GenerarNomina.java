    public GenerarNomina() {
        initComponents();
        this.setTitle("Nóminas generadas");
        this.setResizable(false);
        this.db = new NominaDAOFile();
        Calendar cal = Calendar.getInstance();

        int mesActual = cal.get(Calendar.MONTH);
        int anioActual = cal.get(Calendar.YEAR);

        cal.set(Calendar.DAY_OF_MONTH, 30);
        cal.set(Calendar.MONTH, mesActual);
        cal.set(Calendar.YEAR, anioActual);

        if (cal.get(Calendar.DAY_OF_MONTH) != 30 && cal.get(Calendar.MONTH) == mesActual) {
            cal.set(Calendar.DAY_OF_MONTH, cal.getActualMaximum(Calendar.DAY_OF_MONTH));
        } else if (cal.get(Calendar.MONTH) != mesActual) {
            cal.set(Calendar.MONTH, mesActual);
            cal.set(Calendar.DAY_OF_MONTH, cal.getActualMaximum(Calendar.DAY_OF_MONTH));
        }

        fechaSeleccionada.setDate(cal.getTime());
    }
    
