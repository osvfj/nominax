    private void registrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registrarActionPerformed
      

        int id = Integer.parseInt(txtId.getText());
        String descripcion = txtDescripcion.getText();
        
        try {  
             Optional<Departamento> departamentoEncontrado = this.db.buscarPorId(id);
             if(!departamentoEncontrado.isEmpty()) {
                 Departamento departamento = departamentoEncontrado.get();
            
                 if(!this.validarCampos()) return;
                 
                 departamento.setDescripcion(descripcion);

                 this.db.guardar(departamento);
                 JOptionPane.showMessageDialog(this, "Departamento actualizado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                 reiniciarFormulario();
                 try {
                    this.updateId();
                } catch (IOException ex) {
                    Logger.getLogger(DepartamentoUI.class.getName()).log(Level.SEVERE, null, ex);
                }
                 return;
             }
            
             
            if(!this.validarCampos()) return;
            
            Departamento nuevoDepartamento = new Departamento(id, descripcion);
            this.db.guardar(nuevoDepartamento);
            JOptionPane.showMessageDialog(this, "Departamento guardado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        } catch (HeadlessException | IOException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar usuario: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            this.reiniciarFormulario();
            try {
                this.updateId();
            } catch (IOException ex) {
                Logger.getLogger(DepartamentoUI.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_registrarActionPerformed

