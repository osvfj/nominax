    private void txtIdKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtIdKeyPressed
        
       if(evt.getKeyCode() ==  evt.VK_ENTER){ 
           try {
                Optional<Departamento> departamentoEncontrado = this.db.buscarPorId(Integer.parseInt(txtId.getText()));
                if(departamentoEncontrado.isEmpty()) return;

                Departamento departamento = departamentoEncontrado.get();

                txtId.setText(String.valueOf(departamento.getId()));
                txtId.setEnabled(false);
                txtDescripcion.setText(departamento.getDescripcion());
                lblMensajeEstado.setText("Actualizando registro.");
                lblMensajeEstado.setForeground(Color.RED);
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al buscar el departamento: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_txtIdKeyPressed

    private void txtIdKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtIdKeyReleased
        try {
            int id = Integer.parseInt(txtId.getText());
            if(id < 1) {
                txtId.setText("");
                lblMensajeEstado.setText("El ID no puede <= 0");
                lblMensajeEstado.setForeground(Color.RED);
            } else {
                lblMensajeEstado.setText("");
            }
        } catch (NumberFormatException e) {
               lblMensajeEstado.setText("Debe de ser un entero positivo");
               lblMensajeEstado.setForeground(Color.RED);
               txtId.setText("");
        }
    }//GEN-LAST:event_txtIdKeyReleased

